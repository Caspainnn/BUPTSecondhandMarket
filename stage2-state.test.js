test('stage2 publishing clears that kind draft without losing another kind', () => {
  let state = createPostFormState({ form: { title: '已经发布', images: [{ tempPath: 'a.jpg' }] } })
  state = reducePostFormState(state, { type: 'SWITCH_KIND', direction: 'need', contentType: 'item' })
  state = reducePostFormState(state, { type: 'PATCH_FORM', patch: { title: '尚未发布' } })
  state = reducePostFormState(state, { type: 'SWITCH_KIND', direction: 'provide', contentType: 'item' })
  state = reducePostFormState(state, { type: 'SAVE_SUCCESS', post: { _id: 'p' } })
  state = reducePostFormState(state, { type: 'SWITCH_KIND', direction: 'need', contentType: 'item' })
  assert.equal(state.form.title, '尚未发布')
  state = reducePostFormState(state, { type: 'SWITCH_KIND', direction: 'provide', contentType: 'item' })
  assert.equal(state.form.title, '')
  assert.equal(state.form.images.length, 0)
})
